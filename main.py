# Состояния чатов
chats = {}

async def start(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """Инициализация бота"""
    chat_id = update.effective_chat.id
    chats[chat_id] = {
        "level": 1,
        "categories": set(CATEGORIES),
        "gender": {}
    }
    await update.message.reply_text(
        "🔥 Добро пожаловать в FantaLove! 🔥\n\n"
        "Доступные команды:\n"
        "/level - Установить уровень (1-3)\n"
        "/category - Выбрать категории\n"
        "/fan - Получить случайный фант\n\n"
        "Сейчас активны ВСЕ категории. Уровень: 1"
    )

async def set_level(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """Установка уровня сложности"""
    chat_id = update.effective_chat.id
    if chat_id not in chats:
        await update.message.reply_text("Сначала введите /start")
        return
    
    try:
        level = int(context.args[0])
        if 1 <= level <= 3:
            chats[chat_id]["level"] = level
            await update.message.reply_text(f"✅ Уровень установлен: {level}")
        else:
            await update.message.reply_text("⚠️ Введите уровень от 1 до 3")
    except (IndexError, ValueError):
        await update.message.reply_text("ℹ️ Используйте: /level 1, 2 или 3")

async def show_categories(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """Показать меню категорий"""
    chat_id = update.effective_chat.id
    if chat_id not in chats:
        await update.message.reply_text("Сначала введите /start")
        return

    keyboard = [[cat] for cat in CATEGORIES]
    reply_markup = ReplyKeyboardMarkup(
        keyboard,
        one_time_keyboard=True,
        resize_keyboard=True
    )
    await update.message.reply_text(
        "📋 Выберите категории (повторный выбор отключает):",
        reply_markup=reply_markup
    )

async def toggle_category(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """Включение/отключение категорий"""
    chat_id = update.effective_chat.id
    category = update.message.text
    
    if chat_id not in chats:
        return

    if category not in CATEGORIES:
        await update.message.reply_text("⚠️ Категория не найдена")
        return

    if category in chats[chat_id]["categories"]:
        chats[chat_id]["categories"].remove(category)
        await update.message.reply_text(f"❌ Отключено: {category}")
    else:
        chats[chat_id]["categories"].add(category)
        await update.message.reply_text(f"✅ Включено: {category}")

async def get_fant(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """Генерация случайного фанта"""
    chat_id = update.effective_chat.id
    if chat_id not in chats:
        await update.message.reply_text("Сначала введите /start")
        return

    level = chats[chat_id]["level"]
    active_categories = chats[chat_id]["categories"]

    # Сбор всех доступных фантов
    available = []
    for cat in active_categories:
        if cat in FANTS and level in FANTS[cat]:
            available.extend(FANTS[cat][level])

    if available:
        fant = random.choice(available)
        await update.message.reply_text(f"🎲 Ваш фант:\n\n{fant}\n\nПриятной игры! 😉")
    else:
        await update.message.reply_text("⚠️ Нет фантов для выбранных настроек")

def main():
    """Запуск бота"""
    app = ApplicationBuilder().token(BOT_TOKEN).build()
    
    # Обработчики команд
    app.add_handler(CommandHandler("start", start))
    app.add_handler(CommandHandler("level", set_level))
    app.add_handler(CommandHandler("fan", get_fant))
    app.add_handler(CommandHandler("category", show_categories))
    
    # Обработчик текстовых сообщений (для категорий)
    app.add_handler(
        MessageHandler(
            filters.TEXT & ~filters.COMMAND,
            toggle_category
        )
    )

    print("Бот запущен...")
    app.run_polling()

if __name__ == '__main__':
    main()
